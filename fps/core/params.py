"""Adjustable parameter set (pure logic, no ursina import): builds slider specs from the weapon_data dataclasses, saves / loads JSON.

`ParamStore` holds a LIVE `GameParams`: every game module keeps the same dataclass objects and reads the numbers on each use, so changing a
number here makes the game run on the new value at once (except a few fields copied at build time, marked `restart` or left off the panel, see param_meta.py).

- Sliders are generated by introspection: kind (float / int / on-off / tuple of numbers / choice), defaults taken directly from the dataclass;
  labels, hints, ranges and groups come from `param_meta.py` (a missing range is derived as 0 .. 3 x the default).
- Defaults are snapshotted RIGHT when the store is created (before the user file is loaded), so "reset" always returns to the numbers in weapon_data.
- Saving: only numbers that DIFFER from the default are written, so changing a default in code later still takes effect for numbers never adjusted.
  Loading: reset everything to defaults, then apply the file (missing key = default, unknown key / wrong type = skipped and reported, not an error).
- PER GUN (8/11/2026): every `gun.*` slider belongs to the gun in hand. Its default is THAT gun's number in weapon_data (the Glock's, not the M4's), reset
  ("Mặc định") only touches the gun in hand, and the file keeps each gun apart: `{"version": 2, "values": {shared}, "guns": {"m4": {...}, "glock": {...}}}`.
  A version-1 file (no "guns") was tuned on the M4: its `gun.*` numbers go to the M4. Game tells the store which gun is in hand (`set_gun`) and hands it
  each gun it builds (`register_gun`); numbers loaded for a gun not built yet wait in `_pending` and are written into it when it is built.
"""
import copy
import dataclasses
import json
import math
from dataclasses import dataclass, field
from pathlib import Path

from fps.core import param_meta
from fps.core.safeio import write_text_atomic
from fps.weapon_data import GameParams

FILE_VERSION = 2
LEGACY_GUN = 'm4'          # a version-1 file has no per-gun section: its gun numbers were tuned on the M4


def is_gun_spec(spec) -> bool:
    """The slider belongs to the gun in hand (path 'gun' or 'gun.<...>')."""
    return spec.path == 'gun' or spec.path.startswith('gun.')


class _GunHolder:
    """Lets `resolve(holder, 'gun.accuracy')` read / write a gun that is not `params.gun` (a parked gun, a gun's pristine defaults)."""
    __slots__ = ('gun',)

    def __init__(self, gun):
        self.gun = gun


@dataclass(frozen=True)
class ParamSpec:
    id: str                    # 'gun.accuracy.stand' or 'gun.kick.peak[3]' (a component of a tuple)
    path: str                  # object holding the field: 'gun.accuracy'
    attr: str                  # field name: 'stand'
    index: int                 # component index in the tuple, or None
    group: str
    section: str
    label: str
    hint: str
    kind: str                  # 'float' | 'int' | 'bool' | 'choice'
    lo: float
    hi: float
    step: float
    default: object
    advanced: bool
    restart: bool
    choices: tuple = None      # ((value, text), ...) when kind == 'choice'

    @property
    def decimals(self) -> int:
        return decimals_for(self.step)


@dataclass
class GroupInfo:
    key: str
    title: str
    specs: list = field(default_factory=list)

    def sections(self, show_advanced: bool = True) -> list:
        """[(section title, [spec, ...])] in order; empty sections (after hiding advanced ones) are dropped."""
        out = []
        for spec in self.specs:
            if spec.advanced and not show_advanced:
                continue
            if not out or out[-1][0] != spec.section:
                out.append((spec.section, []))
            out[-1][1].append(spec)
        return out


@dataclass
class LoadReport:
    ok: bool = True
    applied: int = 0
    ignored: list = field(default_factory=list)       # [(key, reason)]
    message: str = ''


# --- format ---
def decimals_for(step: float) -> int:
    if step is None or step <= 0:
        return 2
    return min(4, max(0, math.ceil(-math.log10(step) - 1e-9)))


def format_number(value: float, decimals: int) -> str:
    """Number in Vietnamese style (decimal comma)."""
    return f'{value:.{decimals}f}'.replace('.', ',')


def format_value(spec: ParamSpec, value) -> str:
    if spec.kind == 'bool':
        return 'Bật' if value else 'Tắt'
    if spec.kind == 'choice':
        return dict((_ckey(c), t) for c, t in spec.choices).get(_ckey(value), str(value))
    if spec.kind == 'int':
        return str(int(value))
    return format_number(float(value), spec.decimals)


def _ckey(v):
    """Comparison key for a choice field's value: True / 1 / 'fake' must differ."""
    return (type(v).__name__, v)


def nice_step(lo: float, hi: float) -> float:
    """Drag step 1 / 2 / 5 x 10^k, about 1/100 of the slider length."""
    span = hi - lo
    if span <= 0:
        return 0.01
    raw = span / 100.0
    mag = 10 ** math.floor(math.log10(raw))
    for m in (1, 2, 5, 10):
        if raw <= m * mag * 1.0001:
            return m * mag
    return 10 * mag


def auto_range(default, kind: str) -> tuple:
    """Drag range when param_meta gives none: from 0 to 3 x the default (a negative default: from 3 x the default up to 0; a default of 0: -1..1)."""
    d = float(default)
    if d > 0:
        lo, hi = 0.0, 3.0 * d
    elif d < 0:
        lo, hi = 3.0 * d, 0.0
    else:
        lo, hi = -1.0, 1.0
    if kind == 'int':
        hi = max(hi, 1.0)
    return lo, hi


# --- path / kind ---
def resolve(root, path: str):
    obj = root
    for name in path.split('.'):
        obj = getattr(obj, name)
    return obj


def _same(a, b) -> bool:
    return a == b and type(a) is type(b)


def is_number(v) -> bool:
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _kind_of(value, meta) -> str:
    if meta is not None and meta.choices is not None:
        return 'choice'
    if isinstance(value, bool):
        return 'bool'
    if isinstance(value, int):
        return 'int'
    if isinstance(value, float):
        return 'float'
    raise TypeError(f'không đưa được lên bảng: {value!r}')


def _make_spec(root, group: str, section: str, path: str, attr: str, index, meta) -> ParamSpec:
    obj = resolve(root, path)
    value = getattr(obj, attr)
    if index is not None:
        value = value[index]
    kind = _kind_of(value, meta)
    if kind in ('bool', 'choice'):
        lo = hi = step = 0.0
    else:
        lo, hi = (meta.lo, meta.hi) if meta.lo is not None and meta.hi is not None else auto_range(value, kind)
        step = meta.step if meta.step else (1.0 if kind == 'int' else nice_step(lo, hi))
    sid = f'{path}.{attr}' + (f'[{index}]' if index is not None else '')
    return ParamSpec(id=sid, path=path, attr=attr, index=index, group=group, section=section, label=meta.label, hint=meta.hint,
                     kind=kind, lo=lo, hi=hi, step=step, default=value, advanced=meta.advanced, restart=meta.restart,
                     choices=meta.choices)


def build_specs(root: GameParams) -> list:
    """All sliders in group / section order. Errors (an id missing from the meta table, an odd type) are reported at once, never silently dropped."""
    specs = []
    for gkey, _title, sections in param_meta.GROUPS:
        for stitle, field_ids in sections:
            for fid in field_ids:
                path, attr = fid.rsplit('.', 1)
                meta = param_meta.META[fid]
                value = getattr(resolve(root, path), attr)
                if isinstance(meta, tuple):                       # tuple of numbers: one slider per component
                    if not isinstance(value, tuple) or len(value) != len(meta):
                        raise TypeError(f'{fid}: {len(meta)} thanh nhưng giá trị là {value!r}')
                    for i, m in enumerate(meta):
                        specs.append(_make_spec(root, gkey, stitle, path, attr, i, m))
                else:
                    specs.append(_make_spec(root, gkey, stitle, path, attr, None, meta))
    return specs


def all_field_ids(root: GameParams) -> set:
    """Every field of GameParams ('gun.accuracy.stand', ...), descending into nested dataclasses; used to check the table misses no field."""
    out = set()

    def walk(obj, prefix):
        for f in dataclasses.fields(obj):
            v = getattr(obj, f.name)
            if dataclasses.is_dataclass(v):
                walk(v, f'{prefix}{f.name}.')
            else:
                out.add(f'{prefix}{f.name}')
    walk(root, '')
    return out


class ParamStore:
    def __init__(self, params: GameParams, gun_key: str = None, gun_defaults: dict = None):
        """`gun_key` = key in weapon_data.GUNS of `params.gun` (found by name if omitted). `gun_defaults` = key -> pristine GunData of every gun
        (default: a copy of GUNS); the gun in hand is snapshotted from `params.gun` itself, like the shared defaults."""
        from fps.weapon_data import GUNS
        self.root = params
        self._gun_defaults = {k: copy.deepcopy(g) for k, g in (GUNS if gun_defaults is None else gun_defaults).items()}
        self.gun_key = gun_key or next((k for k, g in self._gun_defaults.items() if g.name == params.gun.name), LEGACY_GUN)
        self._gun_defaults[self.gun_key] = copy.deepcopy(params.gun)
        self._live = {self.gun_key: params.gun}       # gun key -> the LIVE GunData the game uses (the one in hand is params.gun)
        self._pending = {}                            # gun key -> {spec id: value} loaded for a gun not built yet
        self.specs = build_specs(params)
        self.by_id = {s.id: s for s in self.specs}
        self.groups = []
        for gkey, title, _ in param_meta.GROUPS:
            self.groups.append(GroupInfo(gkey, title, [s for s in self.specs if s.group == gkey]))
        self.group_by_key = {g.key: g for g in self.groups}
        self.defaults = {s.id: s.default for s in self.specs}
        self._listeners = []

    # --- listeners: called ONCE per change (the whole batch on load / reset), with the list of changed specs ---
    def subscribe(self, fn):
        self._listeners.append(fn)

    def _notify(self, changed: list):
        if changed:
            for fn in self._listeners:
                fn(changed)

    # --- read / write ---
    def get(self, spec: ParamSpec):
        return self._get_from(self.root, spec)

    @staticmethod
    def _get_from(root, spec: ParamSpec):
        v = getattr(resolve(root, spec.path), spec.attr)
        return v[spec.index] if spec.index is not None else v

    def default_of(self, spec: ParamSpec):
        """The number `spec` returns to on reset: for a gun slider, the gun IN HAND's number in weapon_data."""
        if is_gun_spec(spec):
            pristine = self._gun_defaults.get(self.gun_key)
            if pristine is not None:
                return self._get_from(_GunHolder(pristine), spec)
        return spec.default

    # --- the gun in hand (Game) ---
    def register_gun(self, key: str, gun):
        """A gun was built (Game._build_kit): remember its live data and write in the numbers the file had for it."""
        self._live[key] = gun
        if key not in self._gun_defaults:
            self._gun_defaults[key] = copy.deepcopy(gun)
        holder = _GunHolder(gun)
        for sid, value in self._pending.pop(key, {}).items():
            self._write_into(holder, self.by_id[sid], value)

    def set_gun(self, key: str, gun):
        """Weapon switch: `params.gun` is now `gun` (Game set it). Defaults, 'changed' marks and resets follow this gun from now on."""
        if key not in self._live:
            self.register_gun(key, gun)
        self._live[key] = gun
        self.gun_key = key

    def _write(self, spec: ParamSpec, value):
        self._write_into(self.root, spec, value)

    @staticmethod
    def _write_into(root, spec: ParamSpec, value):
        obj = resolve(root, spec.path)
        if spec.index is None:
            setattr(obj, spec.attr, value)
        else:
            items = list(getattr(obj, spec.attr))
            items[spec.index] = value
            setattr(obj, spec.attr, type(getattr(obj, spec.attr))(items))

    def coerce(self, spec: ParamSpec, raw):
        """Convert a raw value (from the UI or JSON) to the right type and clamp it to the range; raises ValueError if the type is wrong or not finite."""
        if spec.kind == 'bool':
            if not isinstance(raw, bool):
                raise ValueError('cần true / false')
            return raw
        if spec.kind == 'choice':
            for c, _ in spec.choices:
                if _ckey(c) == _ckey(raw):
                    return c
            raise ValueError('không phải một lựa chọn hợp lệ')
        if not is_number(raw) or not math.isfinite(raw):
            raise ValueError('cần một số hữu hạn')
        if spec.kind == 'int':
            if float(raw) != int(raw):
                raise ValueError('cần số nguyên')
            return int(min(max(int(raw), int(spec.lo)), int(spec.hi)))
        return float(min(max(float(raw), spec.lo), spec.hi))

    def set(self, spec: ParamSpec, raw) -> bool:
        """Set a value; returns True if it changed. Wrong type raises ValueError."""
        value = self.coerce(spec, raw)
        if self.get(spec) == value and type(self.get(spec)) is type(value):
            return False
        self._write(spec, value)
        self._notify([spec])
        return True

    def is_default(self, spec: ParamSpec) -> bool:
        return _same(self.get(spec), self.default_of(spec))

    def reset(self, spec: ParamSpec) -> bool:
        return self.reset_many([spec]) > 0

    def reset_many(self, specs) -> int:
        changed = []
        for s in specs:
            if not self.is_default(s):
                self._write(s, self.default_of(s))
                changed.append(s)
        self._notify(changed)
        return len(changed)

    def reset_group(self, key: str) -> int:
        return self.reset_many(self.group_by_key[key].specs)

    def reset_all(self) -> int:
        """'Mặc định' (user choice 8/11/2026): only the GUN IN HAND goes back to its defaults; the shared numbers and the other gun stay."""
        return self.reset_many([s for s in self.specs if is_gun_spec(s)])

    def changed_specs(self, group: str = None) -> list:
        return [s for s in self.specs if (group is None or s.group == group) and not self.is_default(s)]

    # --- save / load ---
    def gun_changes(self, key: str) -> dict:
        """{spec id: value} of gun `key` that differ from that gun's weapon_data numbers (built or still pending)."""
        if key not in self._live:
            return dict(self._pending.get(key, {}))
        live, pristine = _GunHolder(self._live[key]), _GunHolder(self._gun_defaults[key])
        return {s.id: self._get_from(live, s) for s in self.specs if is_gun_spec(s) and not _same(self._get_from(live, s), self._get_from(pristine, s))}

    def gun_keys(self) -> list:
        return sorted(set(self._live) | set(self._pending))

    def to_dict(self) -> dict:
        shared = {s.id: self.get(s) for s in self.specs if not is_gun_spec(s) and not self.is_default(s)}
        guns = {k: d for k in self.gun_keys() if (d := self.gun_changes(k))}
        return {'version': FILE_VERSION, 'values': shared, 'guns': guns}

    def apply_dict(self, data) -> LoadReport:
        """Reset everything (the shared numbers and EVERY gun) to defaults, then apply `data`. Malformed data changes nothing (ok=False)."""
        if not isinstance(data, dict) or not isinstance(data.get('values'), dict):
            return LoadReport(False, message='file không đúng dạng (thiếu "values")')
        guns_raw = data.get('guns', {})
        if not isinstance(guns_raw, dict):
            return LoadReport(False, message='file không đúng dạng ("guns" không phải bảng)')
        report = LoadReport()
        shared, per_gun = [], {}

        def take(key, raw, gun):
            spec = self.by_id.get(key)
            if spec is None:
                report.ignored.append((str(key), 'khoá lạ'))
                return
            if (gun is not None) != is_gun_spec(spec) and gun is None:
                gun = LEGACY_GUN                        # version 1: gun numbers sit in "values" and belong to the M4
            elif gun is not None and not is_gun_spec(spec):
                report.ignored.append((f'{gun}/{key}', 'không phải thông số súng'))
                return
            try:
                value = self.coerce(spec, raw)
            except ValueError as e:
                report.ignored.append((str(key), f'sai kiểu: {e}'))
                return
            (shared if gun is None else per_gun.setdefault(gun, [])).append((spec, value))

        for key, raw in data['values'].items():
            take(key, raw, None)
        for gun, values in guns_raw.items():
            if gun not in self._gun_defaults:
                report.ignored.append((str(gun), 'súng lạ'))
                continue
            if not isinstance(values, dict):
                report.ignored.append((str(gun), 'không phải bảng'))
                continue
            for key, raw in values.items():
                take(key, raw, gun)

        before = {s.id: self.get(s) for s in self.specs}
        for s in self.specs:
            if not is_gun_spec(s):
                self._write(s, s.default)
        for key, gun in self._live.items():
            holder, pristine = _GunHolder(gun), _GunHolder(self._gun_defaults[key])
            for s in self.specs:
                if is_gun_spec(s):
                    self._write_into(holder, s, self._get_from(pristine, s))
        self._pending = {}
        for spec, value in shared:
            self._write(spec, value)
        for gun, items in per_gun.items():
            if gun in self._live:
                holder = _GunHolder(self._live[gun])
                for spec, value in items:
                    self._write_into(holder, spec, value)
            else:
                self._pending.setdefault(gun, {}).update({spec.id: value for spec, value in items})
        report.applied = len(shared) + sum(len(v) for v in per_gun.values())
        self._notify([s for s in self.specs if not _same(self.get(s), before[s.id])])
        extra = f', bỏ qua {len(report.ignored)} mục không dùng được' if report.ignored else ''
        report.message = f'đã nạp {report.applied} giá trị{extra}'
        return report

    def save(self, path) -> LoadReport:
        path = Path(path)
        data = self.to_dict()
        try:
            write_text_atomic(path, json.dumps(data, ensure_ascii=False, indent=2))
        except OSError as e:
            return LoadReport(False, message=f'không ghi được {path.name}: {e}')
        n = len(data['values']) + sum(len(v) for v in data['guns'].values())
        per = ', '.join(f'{k}: {len(v)}' for k, v in data['guns'].items())
        return LoadReport(True, applied=n, message=f'đã lưu {n} giá trị khác mặc định vào {path.name}' + (f' (súng {per})' if per else ''))

    def load(self, path) -> LoadReport:
        path = Path(path)
        try:
            text = path.read_text(encoding='utf-8-sig')       # -sig: a file re-saved by Notepad starts with a BOM
        except FileNotFoundError:
            return LoadReport(False, message=f'chưa có file {path.name} (bấm Lưu trước)')
        except (OSError, UnicodeDecodeError) as e:
            return LoadReport(False, message=f'không đọc được {path.name}: {e}')
        try:
            data = json.loads(text)
        except json.JSONDecodeError as e:
            return LoadReport(False, message=f'{path.name} bị hỏng ({e.msg}), giữ nguyên thông số hiện tại')
        report = self.apply_dict(data)
        if not report.ok:
            report.message = f'{path.name}: {report.message}, giữ nguyên thông số hiện tại'
        return report
